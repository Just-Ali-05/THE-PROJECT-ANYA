export function getHexesByCountry(country) {
  return europeMapData.filter((hex) => hex.country === country);
}

export function getPassableNeighbors(q, r) {
  const directions = [
    { q: 1, r: 0 },
    { q: 1, r: -1 },
    { q: 0, r: -1 },
    { q: -1, r: 0 },
    { q: -1, r: 1 },
    { q: 0, r: 1 },
  ];

  return directions
    .map((dir) => getHexAt(q + dir.q, r + dir.r))
    .filter(
      (hex) => hex && hex.terrain !== "sea" && hex.terrain !== "mountain"
    );
}
